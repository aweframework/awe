#!/usr/bin/env node
'use strict';

/**
 * Generates the REST API reference page of the site (website/docs/rest-api.md) from the OpenAPI description of the AWE REST API.
 *
 * Usage:
 *   node scripts/rest-reference/generate.js [--out <file>] [--snapshot <file>]
 *
 * The OpenAPI document is produced by the Java build, so the website build reads a committed snapshot (data/openapi.json).
 * The snapshot is written by OpenApiSnapshotTest in awe-rest-spring-boot-starter (run it with -Dawe.rest.reference.refresh=true),
 * and the same test fails the Maven build when the snapshot no longer matches the API.
 *
 * The page is regenerated at every start/build and is git-ignored. To make sure a hand-written page is never overwritten, the output
 * file must be missing or carry the generated marker.
 */

const fs = require('node:fs');
const path = require('node:path');

const {MARKER, renderPage, conflictingTags} = require('./render');

const WEBSITE = path.resolve(__dirname, '..', '..');
const DEFAULT_SNAPSHOT = path.join(__dirname, 'data', 'openapi.json');
const DEFAULT_OUT = path.join(WEBSITE, 'docs', 'rest-api.md');

// Set by bin/website-maintenance-docs.sh while it swaps a maintenance line's docs in as the current docs to snapshot them with
// docs:version: that line has no generated REST page, and its docs must be left as they are.
const SKIP_ENV = 'AWE_SKIP_REST_REFERENCE';

function skipped(env) {
	return env[SKIP_ENV] === '1';
}

function parseArgs(argv) {
	const options = {out: DEFAULT_OUT, snapshot: DEFAULT_SNAPSHOT};
	for (let i = 0; i < argv.length; i++) {
		const key = {'--out': 'out', '--snapshot': 'snapshot'}[argv[i]];
		if (!key || argv[i + 1] === undefined) {
			throw new Error(`Usage: generate.js [--out <file>] [--snapshot <file>] (got "${argv.slice(i).join(' ')}")`);
		}
		options[key] = path.resolve(argv[++i]);
	}
	return options;
}

function assertSafeOutput(out) {
	if (fs.existsSync(out) && !fs.readFileSync(out, 'utf8').includes(MARKER)) {
		throw new Error(
			`Refusing to overwrite ${out}: it is not generated by the REST reference (no generated marker). ` +
			'The page is generated now: delete the file.',
		);
	}
}

function build(snapshot) {
	if (!fs.existsSync(snapshot)) {
		throw new Error(
			`Cannot generate the REST reference: ${snapshot} does not exist. Create it with ` +
			'"mvn test -pl awe-framework/awe-starters/awe-rest-spring-boot-starter -Dtest=OpenApiSnapshotTest -Dawe.rest.reference.refresh=true".',
		);
	}
	const spec = JSON.parse(fs.readFileSync(snapshot, 'utf8'));
	const endpoints = Object.values(spec.paths || {}).reduce((count, item) => count + Object.keys(item).length, 0);
	return {page: renderPage(spec), endpoints, conflicts: conflictingTags(spec)};
}

function generate({out = DEFAULT_OUT, snapshot = DEFAULT_SNAPSHOT} = {}) {
	assertSafeOutput(out);
	const {page, endpoints, conflicts} = build(snapshot);
	fs.mkdirSync(path.dirname(out), {recursive: true});
	fs.writeFileSync(out, page);
	return {endpoints, conflicts};
}

/**
 * Generates the page when it is missing or differs from what would be generated now: used by docusaurus.config.js so any
 * docusaurus command, with or without the npm pre-scripts, finds an up to date page.
 */
function ensureGenerated({out = DEFAULT_OUT, snapshot = DEFAULT_SNAPSHOT, env = process.env} = {}) {
	if (skipped(env)) {
		return;
	}
	assertSafeOutput(out);
	const {page} = build(snapshot);
	if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== page) {
		fs.mkdirSync(path.dirname(out), {recursive: true});
		fs.writeFileSync(out, page);
	}
}

if (require.main === module) {
	if (skipped(process.env)) {
		console.log(`REST reference not generated: ${SKIP_ENV}=1 (a maintenance line is being snapshotted)`);
	} else {
		const options = parseArgs(process.argv.slice(2));
		const {endpoints, conflicts} = generate(options);
		console.log(`REST reference written to ${path.relative(process.cwd(), options.out)} (${endpoints} endpoints)`);
		if (conflicts.length > 0) {
			console.warn(`WARNING: tags declared with different descriptions (all shown): ${conflicts.join(', ')}. Make the @Tag descriptions of the controller identical.`);
		}
	}
}

module.exports = {generate, ensureGenerated, parseArgs, DEFAULT_SNAPSHOT, DEFAULT_OUT, SKIP_ENV};
