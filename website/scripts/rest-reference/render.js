'use strict';

/** Renders the REST API reference page (MDX) from the OpenAPI document exported by the Java build. */

const MARKER = '{/* Generated by website/scripts/rest-reference from the OpenAPI snapshot (data/openapi.json). Do not edit: change the Java annotations of the REST controller, then refresh the snapshot with OpenApiSnapshotTest and regenerate. */}';

const METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'];
const FALLBACK_TAG = 'Other';

/** Splits a text into code spans (kept as they are) and the rest. */
function splitCode(text) {
	return text.split(/(``[^]*?``|`[^`]*`)/g);
}

/** Escapes free text for MDX, also inside table cells: pipes, braces, angle brackets (code spans keep their content) and line breaks. */
function escapeText(text) {
	if (text === undefined || text === null) {
		return '';
	}
	return splitCode(String(text))
		.map((part, index) => {
			const piped = part.replace(/\|/g, '\\|');
			if (index % 2 === 1) {
				return piped;
			}
			return piped
				.replace(/\{/g, '\\{')
				.replace(/\}/g, '\\}')
				.replace(/</g, '&lt;')
				.replace(/>/g, '&gt;');
		})
		.join('')
		.replace(/\r?\n/g, '<br/>');
}

function slug(name) {
	return name.toLowerCase().replace(/[^a-z0-9]/g, '');
}

function refName(ref) {
	return ref.split('/').pop();
}

/** Describes the type of a schema in Markdown: links to the schemas section for references. */
function typeOf(schema) {
	if (!schema) {
		return '`any`';
	}
	if (schema.$ref) {
		const name = refName(schema.$ref);
		return `[\`${name}\`](#${slug(name)})`;
	}
	const format = schema.format ? ` (${schema.format})` : '';
	if (schema.type === 'array') {
		return `array of ${typeOf(schema.items)}`;
	}
	if (schema.type === 'object' && schema.additionalProperties !== undefined && !schema.properties) {
		return `map of ${typeOf(schema.additionalProperties === true ? {} : schema.additionalProperties)}`;
	}
	if (schema.enum) {
		return `\`${schema.type || 'any'}\` (${schema.enum.map((value) => `\`${value}\``).join(', ')})`;
	}
	if (!schema.type) {
		return '`any`';
	}
	return `\`${schema.type}\`${format}`;
}

function table(header, rows) {
	return [`| ${header.join(' | ')} |`, `|${header.map(() => '---').join('|')}|`, ...rows.map((row) => `| ${row.join(' | ')} |`)].join('\n');
}

function firstSchema(content) {
	const media = Object.keys(content || {}).sort();
	return media.length > 0 ? content[media[0]].schema : undefined;
}

function describeScheme(scheme) {
	if (!scheme) {
		return '';
	}
	if (scheme.type === 'http') {
		return ['HTTP', scheme.scheme, scheme.bearerFormat].filter(Boolean).join(' ').replace('HTTP bearer JWT', 'HTTP bearer, JWT');
	}
	return scheme.type || '';
}

function renderSecurity(operation, schemes) {
	const requirements = operation.security || [];
	if (requirements.length === 0) {
		return '**Security:** none (public)';
	}
	const alternatives = requirements.map((requirement) => Object.keys(requirement).sort().map((name) => {
		const description = describeScheme(schemes[name]);
		return description ? `\`${name}\` (${escapeText(description)})` : `\`${name}\``;
	}).join(' + '));
	return `**Security:** ${alternatives.join(' or ')}`;
}

function renderOperation(method, route, operation, schemes) {
	const lines = [`### \`${method.toUpperCase()} ${route}\``, ''];
	if (operation.summary) {
		lines.push(`**${escapeText(operation.summary)}**`, '');
	}
	if (operation.description) {
		lines.push(escapeText(operation.description), '');
	}
	lines.push(renderSecurity(operation, schemes), '');
	const parameters = operation.parameters || [];
	if (parameters.length > 0) {
		lines.push('**Parameters**', '', table(
			['Name', 'In', 'Type', 'Required', 'Description'],
			parameters.map((parameter) => [`\`${parameter.name}\``, parameter.in, typeOf(parameter.schema), parameter.required ? 'yes' : 'no', escapeText(parameter.description)]),
		), '');
	}
	const body = operation.requestBody;
	if (body && body.content) {
		lines.push('**Request body**', '');
		for (const media of Object.keys(body.content).sort()) {
			lines.push(`- \`${media}\`: ${typeOf(body.content[media].schema)}`);
		}
		lines.push('');
	}
	const responses = operation.responses || {};
	if (Object.keys(responses).length > 0) {
		lines.push('**Responses**', '', table(
			['Status', 'Description', 'Body'],
			Object.keys(responses).sort().map((status) => {
				const schema = firstSchema(responses[status].content);
				return [`\`${status}\``, escapeText(responses[status].description), schema ? typeOf(schema) : ''];
			}),
		), '');
	}
	return lines;
}

/** Distinct non-empty descriptions declared for each tag name, sorted so the result never depends on the declaration order. */
function tagDescriptions(spec) {
	const byName = new Map();
	for (const tag of spec.tags || []) {
		if (!byName.has(tag.name)) {
			byName.set(tag.name, new Set());
		}
		if (tag.description) {
			byName.get(tag.name).add(tag.description);
		}
	}
	return new Map([...byName].map(([name, set]) => [name, [...set].sort()]));
}

/** Names of the tags declared more than once with different descriptions (all of them are shown on the page). */
function conflictingTags(spec) {
	return [...tagDescriptions(spec)].filter(([, descriptions]) => descriptions.length > 1).map(([name]) => name).sort();
}

function groupByTag(spec) {
	const descriptions = tagDescriptions(spec);
	const groups = new Map();
	for (const route of Object.keys(spec.paths || {}).sort()) {
		for (const method of METHODS.filter((candidate) => spec.paths[route][candidate])) {
			const operation = spec.paths[route][method];
			const tag = (operation.tags && operation.tags[0]) || FALLBACK_TAG;
			if (!groups.has(tag)) {
				groups.set(tag, []);
			}
			groups.get(tag).push({method, route, operation});
		}
	}
	return [...groups.keys()].sort().map((name) => ({name, descriptions: descriptions.get(name) || [], operations: groups.get(name)}));
}

function renderSchemas(schemas) {
	const names = Object.keys(schemas).sort();
	if (names.length === 0) {
		return [];
	}
	const lines = ['## Schemas', ''];
	for (const name of names) {
		const schema = schemas[name];
		lines.push(`### ${name}`, '');
		if (schema.title || schema.description) {
			lines.push(escapeText([schema.title, schema.description].filter(Boolean).join('. ')), '');
		}
		const properties = schema.properties || {};
		if (Object.keys(properties).length === 0) {
			lines.push(`Type: ${typeOf({...schema, properties: undefined})}`, '');
			continue;
		}
		const required = new Set(schema.required || []);
		lines.push(table(
			['Property', 'Type', 'Required', 'Description'],
			Object.keys(properties).sort().map((property) => {
				const definition = properties[property];
				return [`\`${property}\``, typeOf(definition), required.has(property) ? 'yes' : 'no', escapeText(definition.description || definition.title)];
			}),
		), '');
	}
	return lines;
}

function renderAuthentication(schemes) {
	const names = Object.keys(schemes).sort();
	if (names.length === 0) {
		return [];
	}
	return [
		'## Authentication', '',
		...names.map((name) => `- \`${name}\`: ${escapeText(describeScheme(schemes[name]))}. ${escapeText(schemes[name].description)}`.trim()),
		'',
	];
}

function renderPage(spec) {
	const info = spec.info || {};
	const schemes = (spec.components && spec.components.securitySchemes) || {};
	const lines = [
		'---', 'id: rest-api', 'title: REST API reference', 'sidebar_label: REST API reference', '---', '',
		MARKER, '',
		`# ${escapeText(info.title || 'REST API')}`, '',
	];
	if (info.description) {
		lines.push(escapeText(info.description), '');
	}
	if (info.version) {
		lines.push(`**Version:** \`${info.version}\``, '');
	}
	lines.push('This page is generated from the OpenAPI description of the AWE REST API. See the [REST API module](rest-module.md) to enable it and to configure its authentication.', '');
	lines.push(...renderAuthentication(schemes));
	for (const group of groupByTag(spec)) {
		lines.push(`## ${escapeText(group.name)}`, '');
		for (const description of group.descriptions) {
			lines.push(escapeText(description), '');
		}
		for (const {method, route, operation} of group.operations) {
			lines.push(...renderOperation(method, route, operation, schemes));
		}
	}
	lines.push(...renderSchemas((spec.components && spec.components.schemas) || {}));
	return `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

module.exports = {renderPage, conflictingTags, typeOf, escapeText, MARKER};
