#!/usr/bin/env node
'use strict';

/**
 * Generates the documentation audit page (#784) in English and in Spanish:
 *   docs/guides/docs-audit.md and i18n/es/docusaurus-plugin-content-docs/current/guides/docs-audit.md
 *
 * The page lists every current docs page with its area, its last substantive review, its Spanish status and its notes.
 * The area and the Spanish status are read from the file tree, so they never go stale. The review (date, reference, notes) comes
 * from reviews.json: the first rule that names the page wins, and the rule with "default": true covers the rest. Edit
 * reviews.json when you review a page substantively (not for typo fixes), in the same merge request.
 *
 * The pages are regenerated at every start/build and are git-ignored. To make sure a hand-written page is never overwritten,
 * the output file must be missing or carry the generated marker.
 *
 * Usage: node scripts/docs-audit/generate.js [--root <website dir>] [--reviews <file>]
 */

const fs = require('node:fs');
const path = require('node:path');

const WEBSITE = path.resolve(__dirname, '..', '..');
const DEFAULT_REVIEWS = path.join(__dirname, 'reviews.json');
const PAGE = 'guides/docs-audit.md';
const MARKER = '<!-- Generated by scripts/docs-audit/generate.js. Do not edit: edit scripts/docs-audit/reviews.json. -->';
// Pages generated at build time: no Spanish page by hand
const GENERATED = new Set(['properties.md', 'rest-api.md', PAGE]);

const AREAS = {
	api: 'API reference',
	decisions: 'Architecture decisions',
	'design-system': 'Design system',
	guides: 'Guides',
	security: 'Security',
	training: 'Training',
	'': 'Framework and modules'
};

const TEXT = {
	en: {
		id: 'en',
		title: 'Documentation audit',
		intro: 'This page lists every page of the current documentation with its area, its last substantive review, its Spanish ' +
			'status and its notes. It is generated at every build from the files of `website/docs` and from ' +
			'`website/scripts/docs-audit/reviews.json`. A substantive review is a check of the page against the behaviour of the ' +
			'code, not a typo fix; record it in `reviews.json` in the same merge request.',
		summary: (total, translated, generated) =>
			`${total} pages: ${translated} translated to Spanish, ${total - translated - generated} shown in English in the Spanish ` +
			`site, ${generated} generated.`,
		columns: ['Page', 'Area', 'Last review', 'Spanish', 'Notes'],
		spanish: {translated: 'Translated', fallback: 'English fallback', generated: 'Generated'},
		review: (rule) => (rule.reviewed === 'generated' ? rule.ref : `${rule.reviewed} (${rule.ref})`),
		areas: AREAS
	},
	es: {
		id: 'es',
		title: 'Auditoría de la documentación',
		intro: 'Esta página lista todas las páginas de la documentación actual con su área, su última revisión sustancial, su ' +
			'estado en español y sus notas. Se genera en cada build a partir de los ficheros de `website/docs` y de ' +
			'`website/scripts/docs-audit/reviews.json`. Una revisión sustancial es comprobar la página contra el comportamiento del ' +
			'código, no corregir una errata; se anota en `reviews.json` en la misma merge request.',
		summary: (total, translated, generated) =>
			`${total} páginas: ${translated} traducidas al español, ${total - translated - generated} que el sitio en español ` +
			`muestra en inglés, ${generated} generadas.`,
		columns: ['Página', 'Área', 'Última revisión', 'Español', 'Notas'],
		spanish: {translated: 'Traducida', fallback: 'En inglés', generated: 'Generada'},
		review: (rule) => (rule.reviewed === 'generated' ? 'generada a partir de las fuentes' : `${rule.reviewed} (${rule.ref})`),
		areas: {
			api: 'Referencia de la API',
			decisions: 'Decisiones de arquitectura',
			'design-system': 'Sistema de diseño',
			guides: 'Guías',
			security: 'Seguridad',
			training: 'Formación',
			'': 'Framework y módulos'
		}
	}
};

function listPages(dir, base = dir) {
	const pages = [];
	for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
		const file = path.join(dir, entry.name);
		if (entry.isDirectory()) pages.push(...listPages(file, base));
		else if (/\.mdx?$/.test(entry.name)) pages.push(path.relative(base, file).split(path.sep).join('/'));
	}
	return pages.sort();
}

function frontMatterTitle(file) {
	const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(fs.readFileSync(file, 'utf8'));
	const title = match && /^title:\s*(.+?)\s*$/m.exec(match[1]);
	return title ? title[1].replace(/^["']|["']$/g, '') : null;
}

function matches(rule, page) {
	return (rule.paths || []).some((p) => (p.endsWith('/') ? page.startsWith(p) : page === p));
}

function ruleFor(rules, page) {
	return rules.find((rule) => matches(rule, page)) || rules.find((rule) => rule.default) || null;
}

function areaOf(page) {
	const dir = page.includes('/') ? page.split('/')[0] : '';
	return AREAS[dir] ? dir : '';
}

// The page is compiled as MDX: braces and angle brackets would start an expression or a tag, and brackets would end a link
function escapeCell(text) {
	return String(text)
		.replace(/\r?\n/g, ' ')
		.replace(/[<>{}]/g, (char) => `&#${char.charCodeAt(0)};`)
		.replace(/[|[\]]/g, '\\$&');
}

// The rows of the audit: one per English page, with everything the table shows
function collect({root = WEBSITE, reviews = DEFAULT_REVIEWS} = {}) {
	const docs = path.join(root, 'docs');
	const es = path.join(root, 'i18n', 'es', 'docusaurus-plugin-content-docs', 'current');
	const {rules} = JSON.parse(fs.readFileSync(reviews, 'utf8'));
	// The audit page does not list itself, so regenerating it always gives the same table
	return listPages(docs).filter((page) => page !== PAGE).map((page) => {
		const rule = ruleFor(rules, page);
		const spanish = GENERATED.has(page) ? 'generated' : fs.existsSync(path.join(es, page)) ? 'translated' : 'fallback';
		return {
			page,
			title: frontMatterTitle(path.join(docs, page)) || page.replace(/\.mdx?$/, ''),
			area: areaOf(page),
			rule: rule || {reviewed: 'not reviewed', ref: 'no rule in reviews.json', notes: ''},
			spanish
		};
	});
}

function render(rows, text) {
	const counts = {total: rows.length, translated: 0, generated: 0};
	rows.forEach((row) => {
		if (row.spanish === 'translated') counts.translated++;
		if (row.spanish === 'generated') counts.generated++;
	});
	const lines = [
		'---',
		'id: docs-audit',
		`title: ${text.title}`,
		`sidebar_label: ${text.title}`,
		'---',
		'',
		MARKER,
		'',
		`# ${text.title}`,
		'',
		text.intro,
		'',
		text.summary(counts.total, counts.translated, counts.generated),
		'',
		`| ${text.columns.join(' | ')} |`,
		`|${text.columns.map(() => '---').join('|')}|`
	];
	for (const row of rows) {
		// This page lives in guides/: links are relative to it
		const link = `[${escapeCell(row.title)}](${path.posix.relative('guides', row.page)})`;
		lines.push(`| ${[link, text.areas[row.area], escapeCell(text.review(row.rule)), text.spanish[row.spanish],
			escapeCell(row.rule.notes)].join(' | ')} |`);
	}
	return lines.join('\n') + '\n';
}

function writeGenerated(file, content) {
	if (fs.existsSync(file) && !fs.readFileSync(file, 'utf8').includes(MARKER)) {
		throw new Error(`${file} exists and is not generated: not overwriting it`);
	}
	fs.mkdirSync(path.dirname(file), {recursive: true});
	fs.writeFileSync(file, content);
}

function generate(options = {}) {
	const root = options.root || WEBSITE;
	const rows = collect(options);
	const outputs = {
		en: path.join(root, 'docs', PAGE),
		es: path.join(root, 'i18n', 'es', 'docusaurus-plugin-content-docs', 'current', PAGE)
	};
	for (const text of [TEXT.en, TEXT.es]) writeGenerated(outputs[text.id], render(rows, text));
	return {rows, outputs};
}

function parseArgs(argv) {
	const options = {};
	for (let i = 0; i < argv.length; i += 2) {
		const key = {'--root': 'root', '--reviews': 'reviews'}[argv[i]];
		if (!key || argv[i + 1] === undefined) throw new Error(`Unknown or incomplete option ${argv[i]}`);
		options[key] = path.resolve(argv[i + 1]);
	}
	return options;
}

if (require.main === module) {
	try {
		const {rows} = generate(parseArgs(process.argv.slice(2)));
		console.log(`docs-audit: ${rows.length} pages listed`);
	} catch (error) {
		console.error(`docs-audit: ${error.message}`);
		process.exit(1);
	}
}

module.exports = {collect, render, generate, ruleFor, areaOf, escapeCell, parseArgs, MARKER, PAGE, TEXT};
