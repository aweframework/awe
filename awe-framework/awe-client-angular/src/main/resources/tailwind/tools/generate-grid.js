/*
 * Generates compat/grid.generated.css: the Bootstrap 3 grid classes (4 breakpoints x 12 columns, with their offsets,
 * pushes and pulls, plus the AWE-only offset-right) written with @apply on Tailwind. A framework cannot scan the XML screens of
 * every product, so the whole grid is always emitted. Run `npm run compat:grid` after changing the breakpoints or the columns; the Jest test
 * compatGrid.test.js fails when the file is out of date.
 */
const fs = require("fs");
const path = require("path");

const COLUMNS = 12;
// Bootstrap 3 breakpoints (min-width, px). AWE did not change them.
const BREAKPOINTS = [["xs", null], ["sm", 768], ["md", 992], ["lg", 1200]];
const range = (from, to) => Array.from({length: to - from + 1}, (_, index) => from + index);

// Bootstrap rounds its percentages to 8 decimals (8.33333333%); margins have no fraction utility, so they use that value
const percentage = count => `${Number((count / COLUMNS * 100).toFixed(8))}%`;

const fraction = (utility, count, zero) => {
  if (count === 0) {
    return `tw:${utility}-${zero}`;
  }
  if (utility === "ml" || utility === "mr") {
    return `tw:${utility}-[${percentage(count)}]`;
  }
  return count === COLUMNS ? `tw:${utility}-full` : `tw:${utility}-${count}/${COLUMNS}`;
};

const breakpointRules = breakpoint => {
  const names = range(1, COLUMNS).map(count => `.col-${breakpoint}-${count}`);
  const rules = [`${names.join(",\n")} {\n  @apply tw:float-left;\n}`];
  range(1, COLUMNS).reverse().forEach(count => rules.push(`.col-${breakpoint}-${count} {\n  @apply ${fraction("w", count)};\n}`));
  [["pull", "right", "auto"], ["push", "left", "auto"], ["offset", "ml", "[0]"], ["offset-right", "mr", "[0]"]].forEach(([kind, utility, zero]) => {
    range(0, COLUMNS).reverse().forEach(count => {
      rules.push(`.col-${breakpoint}-${kind}-${count} {\n  @apply ${fraction(utility, count, zero)};\n}`);
    });
  });
  return rules.join("\n\n");
};

const indent = text => text.split("\n").map(line => (line ? `  ${line}` : line)).join("\n");

const generateGrid = () => {
  const all = BREAKPOINTS.flatMap(([breakpoint]) => range(1, COLUMNS).map(count => `.col-${breakpoint}-${count}`));
  const parts = [
    "/* Generated by tools/generate-grid.js (npm run compat:grid). Do not edit by hand. */",
    `${all.join(",\n")} {\n  @apply tw:relative tw:min-h-px tw:pl-grid-gutter tw:pr-grid-gutter;\n}`
  ];
  BREAKPOINTS.forEach(([breakpoint, min]) => {
    parts.push(min === null ? breakpointRules(breakpoint) : `@media (min-width: ${min}px) {\n${indent(breakpointRules(breakpoint))}\n}`);
  });
  return `${parts.join("\n\n")}\n`;
};

if (require.main === module) {
  fs.writeFileSync(path.join(__dirname, "..", "compat", "grid.generated.css"), generateGrid());
}

module.exports = {generateGrid};
