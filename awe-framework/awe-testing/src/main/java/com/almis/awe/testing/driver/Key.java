package com.almis.awe.testing.driver;

/**
 * Keys that the browser tests press, independent of the automation tool. Internal preview of the driver port: no
 * compatibility promise yet.
 */
public enum Key {
  /** Escape */
  ESCAPE,
  /** Backspace */
  BACK_SPACE,
  /** Delete */
  DELETE,
  /** Enter */
  ENTER,
  /** Tabulator */
  TAB,
  /** Arrow up */
  ARROW_UP,
  /** Arrow down */
  ARROW_DOWN,
  /** Arrow left */
  ARROW_LEFT,
  /** Arrow right */
  ARROW_RIGHT
}
