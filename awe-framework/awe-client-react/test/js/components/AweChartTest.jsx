  // Spec: Per-Render Reflow on Committed Updates / Layout-changing render
  // After each committed React render the unconstrained useEffect calls redrawRef.current().
  // When a React state update changes the component (e.g. a store model update), setSize
  // must be called to adjust chart dimensions to the (potentially changed) container layout.
  it('per-render reflow: calls setSize after each committed React render triggered by store dispatch', () => {
    jest.useFakeTimers();

    const originalRequestAnimationFrame = window.requestAnimationFrame;
    const originalCancelAnimationFrame = window.cancelAnimationFrame;
    const offsetWidthDescriptor = Object.getOwnPropertyDescriptor(HTMLElement.prototype, 'offsetWidth');
    const offsetHeightDescriptor = Object.getOwnPropertyDescriptor(HTMLElement.prototype, 'offsetHeight');

    window.requestAnimationFrame = jest.fn(cb => setTimeout(cb, 0));
    window.cancelAnimationFrame = jest.fn(id => clearTimeout(id));
    Object.defineProperty(HTMLElement.prototype, 'offsetWidth', {
      configurable: true,
      get() { return 1000; }
    });
    Object.defineProperty(HTMLElement.prototype, 'offsetHeight', {
      configurable: true,
      get() { return 500; }
    });

    const address = { component: 'chart', view: 'report' };

    try {
      const { store } = renderWithProviders(
        <div style={{ width: "1000px", height: "500px" }}><AweChart id="chart" /></div>,
        {
          preloadedState: {
            ...preloadedState,
            components: {
              ...preloadedState.components,
              chart: {
                ...preloadedState.components.chart,
                model: { values },
                attributes: {
                  ...preloadedState.components.chart.attributes,
                  chartModel
                }
              }
            }
          }
        }
      );

      // Allow mount-time reflows to settle.
      act(() => { jest.runAllTimers(); });

      // Capture the setSize call count before the model update.
      const callCountBeforeDispatch = mockChartSetSize.mock.calls.length;

      // Dispatch a model update — this causes React to commit a new render.
      // The unconstrained useEffect must invoke redrawRef.current() → syncChartLayout → setSize.
      act(() => {
        store.dispatch(updateModel(address, { values: values.slice(0, 10) }));
      });
      // Flush debounced reflow (50ms) separately so React has already committed before we advance.
      act(() => { jest.advanceTimersByTime(100); });

      // setSize must have been called at least once more since the dispatch.
      const callCountAfterDispatch = mockChartSetSize.mock.calls.length;
      expect(callCountAfterDispatch).toBeGreaterThan(callCountBeforeDispatch);

      // The most recent setSize call must carry real dimensions (not zero),
      // proving production code ran and applied actual container measurements.
      const lastCall = mockChartSetSize.mock.calls.at(-1);
      const [renderedWidth, renderedHeight, renderedAnimate] = lastCall;
      expect(renderedWidth).toBe(1000);
      expect(renderedHeight).toBe(500);
      expect(renderedAnimate).toBe(false);

      // Triangulation: a SECOND dispatch must also produce another setSize call.
      const callCountBeforeSecond = mockChartSetSize.mock.calls.length;
      act(() => {
        store.dispatch(updateModel(address, { values: values.slice(0, 5) }));
      });
      act(() => { jest.advanceTimersByTime(100); });

      expect(mockChartSetSize.mock.calls.length).toBeGreaterThan(callCountBeforeSecond);
    } finally {
      window.requestAnimationFrame = originalRequestAnimationFrame;
      window.cancelAnimationFrame = originalCancelAnimationFrame;
      if (offsetWidthDescriptor) {
        Object.defineProperty(HTMLElement.prototype, 'offsetWidth', offsetWidthDescriptor);
      } else {
        delete HTMLElement.prototype.offsetWidth;
      }
      if (offsetHeightDescriptor) {
        Object.defineProperty(HTMLElement.prototype, 'offsetHeight', offsetHeightDescriptor);
      } else {
        delete HTMLElement.prototype.offsetHeight;
      }
      jest.useRealTimers();
      mockChartReflow.mockClear();
      mockChartSetSize.mockClear();
      mockChartRedraw.mockClear();
    }
  });

  // Task 3.3: Unmounting before 150ms cancels the delayed reflow so setSize is NOT called
