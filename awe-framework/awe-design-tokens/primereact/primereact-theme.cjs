// The AWE theme of PrimeReact 10 (#885), built from the Lara light theme of the primereact package the React client pins:
// Lara gives the selectors of the PrimeReact 10 markup and the AWE design tokens give every value, following the Aura
// preset of @primeuix/themes 2.0.3 as the design system prototype does. Each colour, font size, font weight, radius,
// spacing, size, shadow, focus ring and transition of Lara is replaced through the equivalence table
// primereact-theme.json; a value of Lara the table does not map fails the build, so a PrimeReact upgrade cannot leak
// its own look. The palette of Lara (its :root blocks) and its font faces are left out.
// The theme is generated by the build of the React client (PrimeReactThemePlugin) and is not kept in the repository.
//
// Usage: node primereact-theme.cjs <primereact folder> <theme file>
const fs = require("fs");
const path = require("path");

const PLUGIN_NAME = "PrimeReactThemePlugin";
const TABLE_FILE = path.join(__dirname, "primereact-theme.json");
const TOKENS_FILE = path.join(__dirname, "..", "tokens.css");
const AURA_LICENSE_FILE = path.join(__dirname, "LICENSE-primeuix-themes.txt");
const LOADER = path.join(__dirname, "primereact-theme-loader.cjs");
// The Lara theme whose selectors the AWE theme keeps
const LARA_THEME = path.join("resources", "themes", "lara-light-indigo", "theme.css");

const COLOR = /#[\da-f]{3,8}\b|rgba?\([^)]*\)|hsla?\([^)]*\)/gi;
const LENGTH = /-?\d*\.?\d+(?:px|rem|em|%)/g;
const DURATION = /\d*\.?\d+m?s\b/g;
// A variable of Lara, with its fallback
const VARIABLE = /var\(--([\w-]+)(?:,[^)]*)?\)/g;
// Properties whose lengths come from the table: spacing and sizes, radii, font sizes
const GEOMETRY = /^(padding|margin)(-(top|right|bottom|left))?$|^(row-|column-)?gap$|^(min-)?(width|height)$/;
const RADIUS = /^border(-(top|bottom)-(left|right))?-radius$/;
// Properties whose whole value is looked up in the table (shadows and focus rings)
const WHOLE_VALUE = /^(box-shadow|outline|outline-offset)$/;
const TRANSITION = /^transition(-duration)?$/;

const readJson = file => JSON.parse(fs.readFileSync(file, "utf8"));
const escapeComment = text => text.replace(/\*\//g, "* /");

/**
 * The --awe-* tokens declared by the AWE token file
 * @param {string} tokensCss Content of tokens.css
 * @returns {Set<string>} Token names
 */
const declaredTokens = tokensCss => new Set([...tokensCss.matchAll(/^\s*(--awe-[\w-]+)\s*:/gm)].map(match => match[1]));

// A table entry is a value or a list of rules ({selector, property, value}) where the first matching rule wins
const resolveEntry = (entry, selector, property) => {
  if (!Array.isArray(entry)) {
    return entry;
  }
  const rule = entry.find(candidate => (!candidate.selector || new RegExp(candidate.selector).test(selector))
    && (!candidate.property || new RegExp(`^(?:${candidate.property})$`).test(property)));
  return rule?.value;
};

// A token name is written as var(); any other value (a keyword, a whole declaration value) is kept as it is
const asCss = value => /^--awe-[\w-]+$/.test(value) ? `var(${value})` : value;

/**
 * Translate the declarations of one Lara rule
 */
class Translator {
  constructor(table) {
    this.table = table;
    this.structural = new Set(table.structural);
    this.overrides = table.overrides.map(override => ({
      ...override,
      selectorPattern: new RegExp(override.selector),
      propertyPattern: new RegExp(`^(?:${override.property})$`)
    }));
    this.unmapped = [];
  }

  fail(selector, property, value, literal) {
    this.unmapped.push(`${selector} { ${property}: ${value} } -> ${literal}`);
    return literal;
  }

  lookup(section, literal, selector, property, value) {
    const mapped = resolveEntry(this.table[section][literal], selector, property);
    return mapped === undefined ? this.fail(selector, property, value, literal) : asCss(mapped);
  }

  // Each length of a value from the given table section, keeping the structural ones (0, 100%, auto...)
  lengths(section, selector, property, value) {
    return value.replace(LENGTH, literal => {
      if (this.structural.has(literal)) {
        return literal;
      }
      const negative = literal.startsWith("-");
      const mapped = this.lookup(section, negative ? literal.slice(1) : literal, selector, property, value);
      return negative ? `calc(-1 * ${mapped})` : mapped;
    });
  }

  translate(selector, property, value) {
    const override = this.overrides.find(candidate => candidate.selectorPattern.test(selector)
      && candidate.propertyPattern.test(property));
    if (override) {
      override.used = true;
      return override.value;
    }
    let result = value.replace(VARIABLE, (match, name) => name in this.table.variables ?
      asCss(this.table.variables[name]) : this.fail(selector, property, value, match));
    if (this.structural.has(result)) {
      return result;
    }
    if (WHOLE_VALUE.test(property)) {
      const whole = resolveEntry(this.table.values[property]?.[result], selector, property);
      if (whole !== undefined) {
        return asCss(whole);
      }
    }
    result = result.replace(COLOR, literal => this.lookup("colors", literal.toLowerCase(), selector, property, value));
    if (property === "font-size") {
      return this.lookup("fontSizes", result, selector, property, value);
    }
    if (property === "font-weight") {
      return this.lookup("fontWeights", result, selector, property, value);
    }
    if (RADIUS.test(property)) {
      return this.lengths("radii", selector, property, result);
    }
    if (GEOMETRY.test(property)) {
      return this.lengths("lengths", selector, property, result);
    }
    if (WHOLE_VALUE.test(property) && result.match(LENGTH)?.some(literal => !this.structural.has(literal))) {
      return this.fail(selector, property, value, result);
    }
    if (TRANSITION.test(property)) {
      return result.replace(DURATION, literal => this.lookup("durations", literal, selector, property, value));
    }
    return result;
  }
}

/**
 * Build the AWE theme from the Lara theme
 * @param {string} laraCss Content of the Lara light theme of primereact
 * @param {{table: object, tokensCss: string, version: string, license: string, auraLicense: string}} options
 *   Equivalence table, AWE token file, primereact version and licence, licence of the Aura preset
 * @returns {string} Theme
 * @throws {Error} When Lara has a value the table does not map, or the table uses a token the token file does not declare
 */
const buildTheme = (laraCss, {table, tokensCss, version, license, auraLicense}) => {
  const translator = new Translator(table);
  const output = [];
  const blocks = [];
  let selectorLines = [];
  let skipDepth = 0;

  laraCss.split(/\r?\n/).forEach((line, index) => {
    const trimmed = line.trim();
    if (skipDepth > 0) {
      skipDepth += (trimmed.endsWith("{") ? 1 : 0) - (trimmed === "}" ? 1 : 0);
      return;
    }
    // Lara writes one selector of a list per line, and one declaration per line ended by a semicolon
    if (trimmed.endsWith(",")) {
      selectorLines.push(trimmed);
      output.push(line);
      return;
    }
    if (trimmed.endsWith("{")) {
      const selector = [...selectorLines, trimmed.slice(0, -1).trim()].join(" ").replace(/\s+/g, " ");
      selectorLines = [];
      // The palette of Lara and its font faces stay out: the tokens give the colours, the client loads the fonts
      if (blocks.length === 0 && (selector === ":root" || selector === "@font-face")) {
        skipDepth = 1;
        return;
      }
      blocks.push(selector);
      output.push(line);
      return;
    }
    if (trimmed === "}") {
      blocks.pop();
      output.push(line);
      return;
    }
    const declaration = /^(\s*)([-\w]+)\s*:\s*(.+?);\s*$/.exec(line);
    if (declaration) {
      const [, indent, property, value] = declaration;
      output.push(`${indent}${property}: ${translator.translate(blocks[blocks.length - 1] || "", property, value)};`);
      return;
    }
    if (trimmed === "" || /^\/\*.*\*\/$/.test(trimmed)) {
      output.push(line);
      return;
    }
    throw new Error(`Unexpected line ${index + 1} of the Lara theme: ${line}`);
  });

  if (translator.unmapped.length > 0) {
    throw new Error(`The PrimeReact theme table (${TABLE_FILE}) does not map ${translator.unmapped.length} values of the`
      + ` Lara theme of primereact ${version}:\n${translator.unmapped.join("\n")}`);
  }
  const unusedOverrides = translator.overrides.filter(override => !override.used);
  if (unusedOverrides.length > 0) {
    throw new Error(`The PrimeReact theme table has overrides that match no declaration of Lara:\n${unusedOverrides
      .map(override => `${override.selector} { ${override.property} }`).join("\n")}`);
  }

  const css = [
    "/*!",
    ` * AWE theme for PrimeReact ${version} (#885) - generated by AWE, do not edit.`,
    " * Selectors: the Lara light theme of primereact (MIT). Values: the AWE design tokens, which follow the Aura preset",
    " * of @primeuix/themes 2.0.3 (MIT, used as reference values only).",
    " *",
    ` * primereact ${version}:`,
    ...escapeComment(license).split("\n").map(text => ` * ${text}`.trimEnd()),
    " *",
    " * @primeuix/themes 2.0.3 (Aura preset):",
    ...escapeComment(auraLicense).split("\n").map(text => ` * ${text}`.trimEnd()),
    " */",
    "/* Variables the PrimeReact components read in their own styles */",
    ":root {",
    ...Object.entries(table.rootVariables).map(([name, token]) => `  ${name}: ${asCss(token)};`),
    "}",
    "",
    ...output
  ].join("\n").replace(/\n{3,}/g, "\n\n");

  const tokens = declaredTokens(tokensCss);
  const missing = [...new Set([...css.matchAll(/var\((--awe-[\w-]+)/g)].map(match => match[1]))]
    .filter(name => !tokens.has(name));
  if (missing.length > 0) {
    throw new Error(`The PrimeReact theme table uses tokens the AWE token file does not declare: ${missing.join(", ")}`);
  }
  return css;
};

/**
 * Read the Lara theme and the licence of a primereact package
 * @param {string} primereactDir Folder of the primereact package
 * @returns {{theme: string, version: string, license: string}} Lara light theme, version and licence
 */
const readPrimeReact = primereactDir => ({
  theme: fs.readFileSync(path.join(primereactDir, LARA_THEME), "utf8"),
  version: readJson(path.join(primereactDir, "package.json")).version,
  license: fs.readFileSync(path.join(primereactDir, "LICENSE.md"), "utf8").trim()
});

/**
 * Build the AWE theme from a Lara theme with the table, the token file and the licences next to this script
 * @param {string} laraCss Lara light theme
 * @param {string} primereactDir Folder of the primereact package (version and licence)
 * @returns {string} Theme
 */
const buildThemeFrom = (laraCss, primereactDir) => {
  const {version, license} = readPrimeReact(primereactDir);
  return buildTheme(laraCss, {
    table: readJson(TABLE_FILE),
    tokensCss: fs.readFileSync(TOKENS_FILE, "utf8"),
    version,
    license,
    auraLicense: fs.readFileSync(AURA_LICENSE_FILE, "utf8").trim()
  });
};

/**
 * Webpack plugin that turns the Lara theme the client imports into the AWE theme
 */
class PrimeReactThemePlugin {
  /**
   * @param {{primereactDir: string}} options Folder of the primereact package
   */
  constructor({primereactDir}) {
    this.primereactDir = primereactDir;
  }

  apply(compiler) {
    // Before the CSS loaders, so they bundle the AWE theme where the client imports the Lara one
    compiler.options.module.rules.push({
      resource: path.join(this.primereactDir, LARA_THEME),
      enforce: "pre",
      use: [{loader: LOADER, options: {primereactDir: this.primereactDir}}]
    });
  }
}

module.exports = {
  LARA_THEME, TABLE_FILE, TOKENS_FILE, AURA_LICENSE_FILE,
  buildTheme, buildThemeFrom, readPrimeReact, declaredTokens, PrimeReactThemePlugin
};

if (require.main === module) {
  const [primereactDir, themeFile] = process.argv.slice(2);
  if (primereactDir && themeFile) {
    const folder = path.resolve(primereactDir);
    fs.writeFileSync(path.resolve(themeFile), buildThemeFrom(readPrimeReact(folder).theme, folder));
  } else {
    // eslint-disable-next-line no-console
    console.error("Usage: node primereact-theme.cjs <primereact folder> <theme file>");
    process.exitCode = 1;
  }
}
